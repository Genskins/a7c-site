  const ORDER = ["it", "pt", "en", "es", "la"];
  const KEY = "a7c.lang";

  function current() {
    const saved = localStorage.getItem(KEY);
    if (saved && I18N[saved]) return saved;
    return "it";
  }

  function apply(lang) {
    const dict = I18N[lang] || I18N.pt;
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      if (dict[k] != null) el.textContent = dict[k];
    });
    // selector estado ativo
    document.querySelectorAll(".lang button").forEach((b) => {
      b.classList.toggle("is-active", b.dataset.lang === lang);
      b.setAttribute("aria-pressed", b.dataset.lang === lang ? "true" : "false");
    });
    localStorage.setItem(KEY, lang);
    if (window.A7C_I18N) window.A7C_I18N.lang = lang;
    document.dispatchEvent(new CustomEvent("a7c:lang", { detail: lang }));
  }

  function buildSelector() {
    const host = document.querySelector(".lang");
    if (!host) return;
    host.innerHTML = "";
    ORDER.forEach((lang, i) => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.dataset.lang = lang;
      btn.textContent = lang.toUpperCase();
      btn.addEventListener("click", () => apply(lang));
      host.appendChild(btn);
      if (i < ORDER.length - 1) {
        const sep = document.createElement("span");
        sep.className = "sep";
        sep.textContent = "·";
        host.appendChild(sep);
      }
    });
  }

  window.A7C_I18N = { apply, current, dict: I18N };

  document.addEventListener("DOMContentLoaded", () => {
    buildSelector();
    apply(current());
  });
